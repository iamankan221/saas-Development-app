import { useState, useRef, useEffect } from "react";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { useParams, useLocation } from "wouter";
import { apiClient, formatINR, formatDate } from "@/lib/api";
import { ArrowLeft, FileText, Share2, Download, MessageCircle, Mail, Smartphone, FileDown, Loader2, Printer, Edit2 } from "lucide-react";
import { generateInvoicePDF, generateInvoicePDFBlob } from "@/lib/invoicePDF";

// ============================================================================
// SHARE MENU
// ============================================================================

function ShareMenu({ bill, customerName, customerPhone, customerEmail }) {
  const [open, setOpen] = useState(false);
  const [sharing, setSharing] = useState(false);
  const ref = useRef(null);

  useEffect(() => {
    const handler = (e) => {
      if (ref.current && !ref.current.contains(e.target)) setOpen(false);
    };
    document.addEventListener("mousedown", handler);
    return () => document.removeEventListener("mousedown", handler);
  }, []);

  // Build detailed invoice message
  const buildInvoiceMessage = () => {
    const items = bill.items || [];
    const total = formatINR(bill.totalAmount);
    const paid = formatINR(bill.paidAmount || 0);
    const status = bill.status === "paid" ? "✅ PAID" : bill.status === "partial" ? "⚠️ PARTIAL PAID" : "🔴 UNPAID";

    let msg = `📄 *INVOICE*\n`;
    msg += `━━━━━━━━━━━━━━━━━━\n`;
    msg += `*Invoice #:* ${bill.billNumber}\n`;
    msg += `*Invoice Code:* ${bill.billCode || "N/A"}\n`;
    msg += `*Date:* ${formatDate(bill.createdAt)}\n`;
    msg += `*Customer:* ${customerName}\n`;
    msg += `*Status:* ${status}\n`;
    msg += `━━━━━━━━━━━━━━━━━━\n\n`;

    if (items.length > 0) {
      msg += `📦 *Items:*\n`;
      items.forEach((item, i) => {
        const qty = Number(item.quantity) || 0;
        const price = formatINR(item.unitPrice);
        msg += `${i + 1}. ${item.itemName} × ${qty} — ${price}\n`;
      });
      msg += `\n`;
    }

    msg += `━━━━━━━━━━━━━━━━━━\n`;
    msg += `💰 *Total Amount:* ${total}\n`;
    msg += `✅ *Paid:* ${paid}\n`;
    if (bill.status !== "paid") {
      const due = Number(bill.totalAmount || 0) - Number(bill.paidAmount || 0);
      msg += `⚠️ *Balance Due:* ${formatINR(due)}\n`;
    }
    msg += `━━━━━━━━━━━━━━━━━━\n\n`;
    msg += `🙏 *Thank you for your business!*\n`;
    msg += `We truly appreciate your trust in us. For any queries regarding this invoice, please don't hesitate to reach out.\n\n`;
    msg += `_Generated by VyaparBook_`;

    return msg;
  };

  // Helper: get full bill data and generate PDF file
  const getBillAndPDF = async () => {
    let fullBill;
    try {
      fullBill = await apiClient.getBill(bill.id);
    } catch {
      fullBill = { ...bill, customer: { name: customerName, phone: customerPhone, email: customerEmail } };
    }
    const pdfFile = await generateInvoicePDFBlob(fullBill);
    return pdfFile;
  };

  const shareWhatsApp = async (e) => {
    e.stopPropagation();
    setSharing(true);
    try {
      const pdfFile = await getBillAndPDF();
      const msg = buildInvoiceMessage();

      // Try Web Share API with file (works on mobile & modern browsers)
      if (navigator.canShare && navigator.canShare({ files: [pdfFile] })) {
        await navigator.share({
          title: `Invoice ${bill.billNumber}`,
          text: msg,
          files: [pdfFile],
        });
      } else {
        // Fallback: auto-download PDF + open WhatsApp with text
        const url = URL.createObjectURL(pdfFile);
        const a = document.createElement("a"); a.href = url; a.download = pdfFile.name; a.click();
        URL.revokeObjectURL(url);

        const phone = customerPhone ? customerPhone.replace(/[^0-9]/g, "") : "";
        const waUrl = phone
          ? `https://wa.me/${phone.startsWith("91") ? phone : "91" + phone}?text=${encodeURIComponent(msg)}`
          : `https://wa.me/?text=${encodeURIComponent(msg)}`;
        window.open(waUrl, "_blank");
      }
    } catch (err) {
      if (err.name !== "AbortError") console.error("Share failed:", err);
    } finally {
      setSharing(false);
      setOpen(false);
    }
  };

  const shareEmail = async (e) => {
    e.stopPropagation();
    setSharing(true);
    try {
      const pdfFile = await getBillAndPDF();
      const body = buildInvoiceMessage().replace(/\*/g, "");
      const subject = `Invoice ${bill.billNumber} - ${formatINR(bill.totalAmount)} | VyaparBook`;

      // Try Web Share API with file
      if (navigator.canShare && navigator.canShare({ files: [pdfFile] })) {
        await navigator.share({
          title: subject,
          text: body,
          files: [pdfFile],
        });
      } else {
        // Fallback: auto-download PDF + open mailto
        const url = URL.createObjectURL(pdfFile);
        const a = document.createElement("a"); a.href = url; a.download = pdfFile.name; a.click();
        URL.revokeObjectURL(url);

        const to = customerEmail || "";
        window.open(`mailto:${to}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`, "_blank");
      }
    } catch (err) {
      if (err.name !== "AbortError") console.error("Share failed:", err);
    } finally {
      setSharing(false);
      setOpen(false);
    }
  };

  const shareSMS = (e) => {
    e.stopPropagation();
    const phone = customerPhone ? customerPhone.replace(/[^0-9]/g, "") : "";
    const smsMsg = `Invoice ${bill.billNumber} | Amount: ${formatINR(bill.totalAmount)} | Status: ${bill.status} | Code: ${bill.billCode || "N/A"}\n\nThank you for your business! - VyaparBook`;
    window.open(`sms:${phone}?body=${encodeURIComponent(smsMsg)}`, "_blank");
    setOpen(false);
  };

  const downloadPDF = async (e) => {
    e.stopPropagation();
    setSharing(true);
    try {
      const pdfFile = await getBillAndPDF();
      const url = URL.createObjectURL(pdfFile);
      const a = document.createElement("a"); a.href = url; a.download = pdfFile.name; a.click();
      URL.revokeObjectURL(url);
    } catch (err) {
      // Fallback to preview
      apiClient.getBill(bill.id).then(fb => generateInvoicePDF(fb)).catch(() => generateInvoicePDF(bill));
    } finally {
      setSharing(false);
      setOpen(false);
    }
  };

  const printPDF = async (e) => {
    e.stopPropagation();
    setSharing(true);
    try {
      let fullBill;
      try {
        fullBill = await apiClient.getBill(bill.id);
      } catch {
        fullBill = { ...bill, customer: { name: customerName, phone: customerPhone, email: customerEmail } };
      }
      generateInvoicePDF(fullBill, { autoPrint: true });
    } finally {
      setSharing(false);
      setOpen(false);
    }
  };

  const actions = [
    { label: "WhatsApp", icon: MessageCircle, onClick: shareWhatsApp, color: "text-green-600 hover:bg-green-50" },
    { label: "Email", icon: Mail, onClick: shareEmail, color: "text-blue-600 hover:bg-blue-50" },
    { label: "SMS", icon: Smartphone, onClick: shareSMS, color: "text-purple-600 hover:bg-purple-50" },
    { label: "PDF Invoice", icon: FileDown, onClick: downloadPDF, color: "text-red-600 hover:bg-red-50" },
    { label: "Print", icon: Printer, onClick: printPDF, color: "text-orange-600 hover:bg-orange-50" },
  ];

  return (
    <div className="relative" ref={ref}>
      <button
        type="button"
        className={`p-1.5 rounded-lg transition-colors ${open ? "bg-blue-50 text-blue-600" : "text-gray-400 hover:text-gray-600 hover:bg-gray-100"}`}
        onClick={(e) => { e.stopPropagation(); setOpen(!open); }}
        title="Share bill"
        disabled={sharing}
      >
        {sharing ? <Loader2 className="w-4 h-4 animate-spin text-blue-500" /> : <Share2 className="w-4 h-4" />}
      </button>

      {open && (
        <div className="absolute right-0 top-full mt-1 z-30 bg-white border border-gray-200 rounded-xl shadow-lg py-1 w-40">
          {actions.map(({ label, icon: Icon, onClick, color }) => (
            <button
              key={label}
              type="button"
              className={`w-full flex items-center gap-2.5 px-3 py-2 text-sm font-medium transition-colors ${color}`}
              onClick={onClick}
              disabled={sharing}
            >
              <Icon className="w-4 h-4" />
              {label}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

